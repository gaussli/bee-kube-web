function getUserPage(params: UserQueryReq): PageVo<UserResp> {
  const { id, username, nickname, status, page = 1, pageSize = 10 } = params || {}

  let filtered = [...mockUsers]
  if (id && id === username && nickname === username) {
    filtered = filtered.filter(
      u => u.id == id || u.username.includes(username.toLowerCase()) || u.nickname.includes(nickname),
    )
  } else {
    if (username) {
      filtered = filtered.filter(u => u.username.includes(username))
    }
    if (nickname) {
      filtered = filtered.filter(u => u.nickname.includes(nickname))
    }
  }
  if (status) {
    filtered = filtered.filter(u => u.status === status)
  }

  const total = filtered.length
  const start = (page - 1) * pageSize
  const end = start + pageSize
  const list = filtered.slice(start, end)
  return { list, total, page, pageSize }
}

export default [
  {
    method: 'get',
    url: '/system/users',
    handler: ({ params }: { params: any }) => getUserPage(params),
  },
]
